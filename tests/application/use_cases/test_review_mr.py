def test_publish_review_multiple_comments(review_mr_use_case, mock_vcs_service):
    """Testa publicação de review com múltiplos comentários."""
    # Arrange
    project_path = "test/project"
    mr_iid = 123
    review_text = """Primeiro comentário
---
Segundo comentário
---
Terceiro comentário"""

    # Act
    review_mr_use_case.publish_review(project_path, mr_iid, review_text)

    # Assert
    mock_vcs_service.post_comments_on_merge_request.assert_called_once()
    call_args = mock_vcs_service.post_comments_on_merge_request.call_args

    assert call_args[0][0] == project_path
    assert call_args[0][1] == mr_iid
    comments = call_args[0][2]
    assert len(comments) == 3

    # Verifica que TODOS os comentários têm prefixo e sufixo
    prefix = "<!-- agent-review-bot -->"
    suffix = "Generated by AI with ❤️"

    for i, comment in enumerate(comments):
        assert prefix in comment, f"Comentário {i+1} deve ter prefixo"
        assert suffix in comment, f"Comentário {i+1} deve ter sufixo"
        # Verifica que o conteúdo do comentário está presente
        if i == 0:
            assert "Primeiro comentário" in comment
        elif i == 1:
            assert "Segundo comentário" in comment
        else:
            assert "Terceiro comentário" in comment


