def test_execute_cache_miss(review_mr_use_case, mock_vcs_service, mock_llm_service, mock_storage_service, mock_cache_service):
    """Test the successful execution when the review is not in the cache."""
    # Arrange
    project_id = "test/project"
    mr_iid = 1
    changes_data = {"changes": [{"diff": "..."}]}
    llm_review = "This is a great change!"
    saved_path = "reviews/2023-10-27/1/review.md"

    mock_vcs_service.get_merge_request_changes.return_value = changes_data
    mock_cache_service.get.return_value = None  # Cache miss
    mock_llm_service.analyze_code_changes.return_value = llm_review
    mock_storage_service.save_review.return_value = saved_path

    # Act
    result = review_mr_use_case.execute(project_id, mr_iid, mock_llm_service)

    # Assert
    mock_vcs_service.get_merge_request_changes.assert_called_once_with(project_id, mr_iid)

    expected_prompt = f"Base prompt: {review_mr_use_case._load_prompt_context('prompt_contexts')} {changes_data}"
    mock_cache_service.get.assert_called_once_with(expected_prompt)
    mock_llm_service.analyze_code_changes.assert_called_once_with(expected_prompt)
    mock_cache_service.set.assert_called_once_with(expected_prompt, llm_review)

    # Verifica que save_review foi chamado com o review completo (com prefixo/sufixo)
    expected_full_review = f"<!-- agent-review-bot -->\n\n{llm_review}\n\nGenerated by AI with ❤️"
    mock_storage_service.save_review.assert_called_once_with(mr_iid, expected_full_review)

    # Verifica o retorno inclui todos os campos esperados
    assert "review" in result
    assert "full_review" in result
    assert "parsed_comments" in result
    assert "review_file_path" in result
    assert result["review"] == llm_review
    assert result["review_file_path"] == saved_path
    assert result["full_review"] == expected_full_review


