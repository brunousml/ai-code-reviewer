def test_publish_review_all_comments_have_prefix_and_suffix(review_mr_use_case, mock_vcs_service):
    """Testa que TODOS os comentários têm prefixo e sufixo, não apenas o primeiro e último."""
    # Arrange
    project_path = "test/project"
    mr_iid = 123
    review_text = """Comentário 1
---
Comentário 2
---
Comentário 3
---
Comentário 4"""

    prefix = "<!-- agent-review-bot -->"
    suffix = "Generated by AI with ❤️"

    # Act
    review_mr_use_case.publish_review(project_path, mr_iid, review_text)

    # Assert
    call_args = mock_vcs_service.post_comments_on_merge_request.call_args
    comments = call_args[0][2]

    # Verifica que TODOS os 4 comentários têm prefixo e sufixo
    assert len(comments) == 4

    for i, comment in enumerate(comments, 1):
        assert prefix in comment, f"Comentário {i} deve ter prefixo"
        assert suffix in comment, f"Comentário {i} deve ter sufixo"
        # Verifica que o prefixo está no início e o sufixo no final
        assert comment.startswith(prefix), f"Comentário {i} deve começar com prefixo"
        assert comment.endswith(suffix), f"Comentário {i} deve terminar com sufixo"
